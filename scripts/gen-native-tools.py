#!/usr/bin/env python3
"""Generate the native port's job and learner-file tool definitions
(docs/native-macos-m6.md), and the graph and extraction tools plus the
extraction prompts (docs/native-macos-m7.md), from the TS golden dump, so
names, descriptions, schemas and prompts stay byte-identical to the TS:

    npx tsx scripts/dump-agent-golden.ts && python3 scripts/gen-native-tools.py
"""
import json, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent
GOLDEN = ROOT / "macos/Packages/LHKit/Tests/LHAgentTests/Golden/tools-teacher.json"
OUT = ROOT / "macos/Packages/LHKit/Sources/LHAgent/Jobs/GeneratedToolDefinitions.swift"
NAMES = ["read", "ls", "find", "grep", "research", "demo", "visual", "pdf"]

def lit(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t") + '"'

def schema(js, indent):
    pad = "\t" * indent
    t = js.get("type")
    desc = f", description: {lit(js['description'])}" if "description" in js else ""
    if t == "object":
        req = set(js.get("required", []))
        props = []
        for k, v in js.get("properties", {}).items():
            inner = schema(v, indent + 1)
            props.append(f'{pad}\t.init({lit(k)}, {inner}{"" if k in req else ".optional()"}),')
        return "JSONSchema.object(properties: [\n" + "\n".join(props) + f"\n{pad}]{desc})"
    if t == "string":
        if "minLength" in js:
            return f"JSONSchema.string(minLength: {js['minLength']}{desc})"
        return f"JSONSchema.string({desc[2:]})" if desc else "JSONSchema.string()"
    if t == "integer":
        if "minimum" in js:
            return f"JSONSchema.integer(minimum: {js['minimum']}{desc})"
        return f"JSONSchema.integer({desc[2:]})" if desc else "JSONSchema.integer()"
    if t == "array":
        mi = f", minItems: {js['minItems']}" if "minItems" in js else ""
        return f"JSONSchema.array({schema(js['items'], indent)}{mi}{desc})"
    if t == "boolean":
        return f"JSONSchema.boolean({desc[2:]})" if desc else "JSONSchema.boolean()"
    raise SystemExit(f"unsupported schema: {js}")

tools = {t["name"]: t for t in json.loads(GOLDEN.read_text())}
out = ["// GENERATED by scripts/gen-native-tools.py from the TS golden dump — do not edit.",
       "// Names, descriptions and schemas byte-identical to src/agent/tools/*.ts.", "", "import LHCore", "",
       "enum GeneratedTools {"]
for n in NAMES:
    t = tools[n]
    out.append(f"\tstatic let {n}Description = {lit(t['description'])}")
    out.append(f"\tstatic let {n}Schema = {schema(t['input_schema'], 1)}")
out.append("}")
OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n".join(out) + "\n")
print("wrote", OUT.relative_to(ROOT))

# M7: the prober's graph tools and the extraction stages.
GOLD = ROOT / "macos/Packages/LHKit/Tests/LHAgentTests/Golden"
prober = {t["name"]: t for t in json.loads((GOLD / "tools-prober.json").read_text())}
extraction = json.loads((GOLD / "extraction.json").read_text())
ex = {t["name"]: t for t in extraction["tools"]}
entries = [("proberListSessions", prober["list_sessions"]), ("proberListPropositions", prober["list_propositions"]),
	("submitFindings", ex["submit_findings"]), ("submitFindingsNotes", ex["submit_findings_notes"]), ("submitReview", ex["submit_review"]),
	("auditorFind", ex["find"]), ("auditorListSessions", ex["list_sessions"]), ("auditorListPropositions", ex["list_propositions"])]
out = ["// GENERATED by scripts/gen-native-tools.py from the TS golden dump — do not edit.",
	"// Names, descriptions and schemas byte-identical to src/agent/tools/graph.ts and",
	"// src/agent/subagents/extraction.ts.", "", "import LHCore", "", "enum GeneratedGraphTools {"]
for key, t in entries:
	out.append(f"\tstatic let {key}Description = {lit(t['description'])}")
	out.append(f"\tstatic let {key}Schema = {schema(t['input_schema'], 1)}")
out.append("}")
OUT2 = ROOT / "macos/Packages/LHKit/Sources/LHAgent/Extraction/GeneratedGraphToolDefinitions.swift"
OUT2.parent.mkdir(parents=True, exist_ok=True)
OUT2.write_text("\n".join(out) + "\n")
print("wrote", OUT2.relative_to(ROOT))
PROMPTS = ROOT / "macos/Packages/LHKit/Sources/LHResources/Resources/prompts/extraction"
PROMPTS.mkdir(parents=True, exist_ok=True)
for key, file in [("extractor", "extractor.md"), ("notesExtractor", "notes-extractor.md"), ("auditor", "auditor.md")]:
	(PROMPTS / file).write_text(extraction["prompts"][key])
	print("wrote", (PROMPTS / file).relative_to(ROOT))
